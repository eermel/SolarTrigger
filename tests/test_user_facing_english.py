def test_known_operator_facing_french_strings_are_gone():
    failures = []
    for relative, phrases in FORBIDDEN_BY_FILE.items():
        path = ROOT / relative
        assert path.exists(), f"missing audited file: {relative}"
        text = path.read_text(encoding="utf-8")
        for phrase in phrases:
            if phrase in text:
                failures.append(f"{relative}: {phrase!r}")
    assert not failures, "French operator-facing text remains:\n" + "\n".join(failures)


